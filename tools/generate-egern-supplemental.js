#!/usr/bin/env node
'use strict';

const fs = require('node:fs');
const path = require('node:path');

const REPO_ROOT = path.resolve(__dirname, '..');
const SOURCE_DIR = path.join(REPO_ROOT, 'rulesets/supplemental/clash');
const OUTPUT_DIR = path.join(REPO_ROOT, 'rulesets/supplemental/egern');

const SKIP_FILES = new Set([
  'local-process-direct.list',
  'work-process.list',
]);

const TYPE_MAP = new Map([
  ['DOMAIN', 'domain_set'],
  ['DOMAIN-SUFFIX', 'domain_suffix_set'],
  ['DOMAIN-KEYWORD', 'domain_keyword_set'],
  ['IP-CIDR', 'ip_cidr_set'],
  ['IP-CIDR6', 'ip_cidr6_set'],
]);

function yamlQuote(value) {
  return JSON.stringify(value);
}

function parseClashList(filePath) {
  const buckets = new Map();
  let noResolve = false;
  for (const rawLine of fs.readFileSync(filePath, 'utf8').split(/\r?\n/)) {
    const line = rawLine.trim();
    if (!line || line.startsWith('#')) continue;
    const parts = line.split(',').map((part) => part.trim()).filter(Boolean);
    const type = parts[0];
    const value = parts[1];
    // Mixed sets retain domains/IPs; Egern has no PROCESS-NAME rule.
    if (type === "PROCESS-NAME") continue;
    if (!TYPE_MAP.has(type)) {
      throw new Error(`Unsupported Egern supplemental rule type in ${filePath}: ${line}`);
    }
    const bucket = TYPE_MAP.get(type);
    if (!buckets.has(bucket)) buckets.set(bucket, []);
    buckets.get(bucket).push(value);
    if (parts.includes('no-resolve')) noResolve = true;
  }
  return { buckets, noResolve };
}

function renderRuleSet(fileName, parsed) {
  const lines = [
    '# Generated by tools/generate-egern-supplemental.js',
    '# Source: rulesets/supplemental/clash/' + fileName.replace(/\.yaml$/, '.list'),
  ];
  if (parsed.noResolve) lines.push('no_resolve: true');
  for (const key of ['domain_set', 'domain_suffix_set', 'domain_keyword_set', 'ip_cidr_set', 'ip_cidr6_set']) {
    const values = parsed.buckets.get(key);
    if (!values || values.length === 0) continue;
    lines.push(`${key}:`);
    for (const value of values) lines.push(`  - ${yamlQuote(value)}`);
  }
  return `${lines.join('\n')}\n`;
}

function main() {
  fs.mkdirSync(OUTPUT_DIR, { recursive: true });
  const generated = [];
  for (const entry of fs.readdirSync(SOURCE_DIR, { withFileTypes: true })) {
    if (!entry.isFile() || !entry.name.endsWith('.list') || SKIP_FILES.has(entry.name)) continue;
    const parsed = parseClashList(path.join(SOURCE_DIR, entry.name));
    const outputName = entry.name.replace(/\.list$/, '.yaml');
    fs.writeFileSync(path.join(OUTPUT_DIR, outputName), renderRuleSet(outputName, parsed), 'utf8');
    generated.push(outputName);
  }
  console.log(`Generated ${generated.length} Egern supplemental rule sets`);
}

main();
