for (const [mode, pattern] of [
  ['rpc-error', /initialize.*-32000/], ['rpc-timeout', /RPC.*initialize.*timed out/],
  ['exit', /exited.*9/], ['bad-json', /invalid JSON/], ['failed', /turn.*failed/], ['interrupted', /turn.*interrupted/],
  ['approval', /interactive.*request/], ['unknown-request', /interactive.*request/]
]) {
  test(`rejects ${mode} without reporting success`, async t => {
    const f = fixture(t, mode);
    await assert.rejects(require('../lib/local-codex-app-server').runCodexTask({ ...f.options, rpcTimeoutMs: mode === 'rpc-timeout' ? 150 : 3000 }), err => {
      assert.match(err.message, pattern);
      assert(!err.message.includes('secret-that-must-not-leak'));
      return true;
    });
    if (mode === 'approval') assert.deepEqual(f.read().find(x => x.id === 'server-1').result, { decision: 'decline' });
    if (mode === 'unknown-request') assert.equal(f.read().find(x => x.id === 'server-1').error.code, -32601);
  });
}

