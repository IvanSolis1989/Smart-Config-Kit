// A separate Node process exercises real JSONL pipes, process exit and cancellation.
const SERVER = String.raw`
const fs = require('node:fs');
const readline = require('node:readline');
const mode = process.argv[2];
const log = process.argv[3];
fs.writeFileSync(log + '.server', String(process.pid));
const send = x => process.stdout.write(JSON.stringify(x) + '\r\n');
const note = (method, params) => send({ method, params });
const complete = (status = 'completed') => note('turn/completed', {
  threadId: 'thread-1', turn: { id: 'turn-1', status, items: [], error: status === 'failed' ? { message: 'fixture failure' } : null }
});
let initialized = false;
readline.createInterface({ input: process.stdin }).on('line', line => {
  const m = JSON.parse(line);
  fs.appendFileSync(log, JSON.stringify(m) + '\n');
  if (m.method === 'initialized') { initialized = true; return; }
  if (m.method === 'initialize') {
    if (mode === 'rpc-timeout') return;
    if (mode === 'rpc-error') return send({ id: m.id, error: { code: -32000, message: 'fixture RPC failure' } });
    return send({ id: m.id, result: { userAgent: 'fixture' } });
  }
  if (m.method === 'thread/start') {
    if (!initialized) process.exit(12);
    // Generated by the installed Codex App binary: SandboxMode is kebab-case,
    // while turn/start's SandboxPolicy discriminator remains camelCase.
    if (!['read-only', 'workspace-write', 'danger-full-access'].includes(m.params.sandbox)) {
      return send({ id: m.id, error: { code: -32600, message: 'Invalid sandbox mode' } });
    }
    return send({ id: m.id, result: { thread: { id: 'thread-1', ephemeral: false } } });
  }
  if (m.method === 'thread/name/set') return send({ id: m.id, result: {} });
  if (m.method === 'turn/interrupt') {
    fs.writeFileSync(log + '.interrupted', 'yes');
    return send({ id: m.id, result: {} });
  }
  if (m.method !== 'turn/start') return;
  if (!fs.existsSync(log + '.saved')) process.exit(13);
  if (mode === 'exit') { process.stderr.write('secret-that-must-not-leak'); process.exit(9); }
  if (mode === 'bad-json') { process.stdout.write('broken JSON\n'); return; }
  const started = { id: m.id, result: { turn: { id: 'turn-1', status: 'inProgress', items: [], error: null } } };
  if (mode !== 'early') send(started);
  note('turn/started', { threadId: 'thread-1', turn: { id: 'turn-1', status: 'inProgress', items: [], error: null } });
  if (mode === 'descendant') {
    const child = require('node:child_process').spawn(process.execPath, ['-e',
      'const fs = require("node:fs"); const beat = () => fs.appendFileSync(process.argv[1], "tick\\n"); beat(); setInterval(beat, 10);',
      log + '.heartbeat'], { stdio: 'ignore', windowsHide: true });
    fs.writeFileSync(log + '.child', String(child.pid));
    return;
  }
  if (['timeout', 'cancel', 'tool-only'].includes(mode)) {
    note('item/completed', { threadId: 'thread-1', turnId: 'turn-1', item: { id: 'tool', type: 'commandExecution', status: 'completed' } });
    return;
  }
  if (mode === 'approval' || mode === 'unknown-request') {
    send({ id: 'server-1', method: mode === 'approval' ? 'item/commandExecution/requestApproval' : 'item/tool/requestUserInput', params: { threadId: 'thread-1', turnId: 'turn-1', itemId: 'tool' } });
    return;
  }
  note('item/completed', { threadId: 'other-thread', turnId: 'turn-1', item: { id: 'other', type: 'agentMessage', text: 'wrong thread' } });
  note('item/completed', { threadId: 'thread-1', turnId: 'other-turn', item: { id: 'other', type: 'agentMessage', text: 'wrong turn' } });
  note('turn/completed', { threadId: 'other-thread', turn: { id: 'turn-1', status: 'completed' } });
  note('item/completed', { threadId: 'thread-1', turnId: 'turn-1', item: { id: 'comment', type: 'agentMessage', text: 'working', phase: 'commentary' } });
  const bytes = Buffer.from(JSON.stringify({ method: 'item/completed', params: { threadId: 'thread-1', turnId: 'turn-1', item: { id: 'answer', type: 'agentMessage', text: '完成 ✓', phase: 'final_answer' } } }) + '\r\n');
  const split = bytes.indexOf(Buffer.from('完成')) + 1;
  process.stdout.write(bytes.subarray(0, split));
  setTimeout(() => {
    process.stdout.write(bytes.subarray(split));
    complete(mode === 'failed' ? 'failed' : mode === 'interrupted' ? 'interrupted' : 'completed');
    if (mode === 'early') send(started);
  }, 10);
});
setInterval(() => {}, 1000);
`;

function fixture(t, mode = 'success') {
  const cwd = fs.mkdtempSync(path.join(os.tmpdir(), 'scki-codex-rpc-'));
  t.after(() => fs.rmSync(cwd, { recursive: true, force: true }));
  const server = path.join(cwd, 'server.js');
  const log = path.join(cwd, 'messages.jsonl');
  fs.writeFileSync(server, SERVER);
  return {
    log,
    read: () => fs.existsSync(log) ? fs.readFileSync(log, 'utf8').trim().split('\n').filter(Boolean).map(JSON.parse) : [],
    options: { command: process.execPath, args: [server, mode, log], cwd, prompt: 'inspect fixture', title: 'Issue fixture', timeoutMs: 5000,
      onThread: async id => { assert.equal(id, 'thread-1'); await new Promise(resolve => setTimeout(resolve, 15)); fs.writeFileSync(log + '.saved', id); } }
  };
}

test('exports runCodexTask', () => {
  assert.equal(typeof require('../lib/local-codex-app-server').runCodexTask, 'function');
});

for (const mode of ['success', 'early']) {
  test(`reads chunked UTF-8 and CRLF and waits for the matching turn (${mode})`, async t => {
    const { runCodexTask } = require('../lib/local-codex-app-server');
    const f = fixture(t, mode);
    const events = [];
    const schema = { type: 'object', properties: { answer: { type: 'string' } } };
    const result = await runCodexTask({ ...f.options, outputSchema: schema, onEvent: event => events.push(event) });
    assert.deepEqual(result, { threadId: 'thread-1', turnId: 'turn-1', status: 'completed', text: '完成 ✓' });
    const messages = f.read();
    assert.deepEqual(messages[0].params.clientInfo, { name: 'scki_issue_bridge', version: '1.0.0' });
    const thread = messages.find(x => x.method === 'thread/start');
    assert.equal(thread.params.sandbox, 'workspace-write');
    assert.equal(thread.params.ephemeral, false);
    assert.deepEqual(messages.find(x => x.method === 'thread/name/set').params, { threadId: 'thread-1', name: 'Issue fixture' });
    const turn = messages.find(x => x.method === 'turn/start');
    assert.equal(turn.params.approvalPolicy, 'never');
    assert.deepEqual(turn.params.input, [{ type: 'text', text: 'inspect fixture' }]);
    assert.deepEqual(turn.params.sandboxPolicy, { type: 'workspaceWrite', writableRoots: [f.options.cwd], networkAccess: true });
    assert.deepEqual(turn.params.outputSchema, schema);
    assert(events.some(x => x.method === 'turn/completed'));
  });
}

