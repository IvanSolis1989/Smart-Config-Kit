'use strict';

const assert = require('node:assert/strict');
const crypto = require('node:crypto');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const zlib = require('node:zlib');
const test = require('node:test');
const { hash, validateSupplementalPatch, packStagedOutput, currentFusedHashes, validateSnapshotBindings } = require('../lib/egern-traffic-snapshot');
const { listGeneratedEgernAssetRecords } = require('../lib/egern-generation-manifest');
const generator = require('../generate-egern-from-cmfa');

const prefix = 'rulesets/generated/fused/';
const digest = bytes => crypto.createHash('sha256').update(bytes).digest('hex');
const oid = bytes => crypto.createHash('sha1').update(`blob ${bytes.length}\0`).update(bytes).digest('hex');
const hosts = ['a-api.anthropic.com', 'a-cdn.anthropic.com'];
const added = hosts.map(host => `DOMAIN,${host}`);
const payload = entries => `payload:\n${entries.map(entry => `  - ${JSON.stringify(entry)}\n`).join('')}`;
const native = (id, domains, tail = '') => `# Generated by tools/generate-egern-from-cmfa.js\n# Source id: provider-${id}-domain\n# Source URL: frozen-lineage\ndomain_set:\n${domains.map(host => `  - ${JSON.stringify(host)}\n`).join('')}${tail}`;

function fixture() {
  const baseline = new Map(), currentFiles = new Map();
  const ids = ['scki-fused-004-ai', 'scki-fused-006-ad'];
  const changes = ids.map((id, index) => ({ id, added: index ? [] : [...added], deleted: index ? [...added] : [] }));
  const segments = ids.map(id => ({ id, files: {
    domain: { source: `${id}-domain.yaml`, file: `${id}-domain.mrs` },
    ...Object.fromEntries(['clash', 'surge', 'quantumultx'].map(platform => [platform, { file: `${id}.list` }])),
    egern: { file: `${id}.yaml` }, sing_box: { source: `${id}.json`, file: `${id}.srs` },
  } }));
  for (const [index, row] of segments.entries()) {
    for (const [platform, file] of [
      ['mihomo', row.files.domain.source], ['mihomo', row.files.domain.file],
      ...['clash', 'surge', 'quantumultx'].map(platform => [platform, row.files[platform].file]),
      ['egern', row.files.egern.file], ['sing-box', row.files.sing_box.source], ['sing-box', row.files.sing_box.file],
    ]) {
      const relative = `${prefix}${platform}/${file}`;
      const old = file.endsWith('-domain.yaml') ? payload(index ? [...hosts, '+.same.test'] : ['keep.test']) : 'frozen native payload\n';
      const next = file.endsWith('-domain.yaml') ? payload(index ? ['+.same.test'] : ['keep.test', ...hosts]) : 'accepted native payload\n';
      baseline.set(relative, Buffer.from(old)); currentFiles.set(relative, Buffer.from(next));
    }
  }
  const unrelated = `${prefix}mihomo/unchanged-residual.yaml`;
  baseline.set(unrelated, Buffer.from('payload:\n  - GEOIP,CN\n'));
  currentFiles.set(unrelated, baseline.get(unrelated));
  const fingerprint = 'a'.repeat(64), sourceFingerprint = 'b'.repeat(64), currentFingerprint = 'c'.repeat(64);
  const baselineManifestText = JSON.stringify({ segments, payload_fingerprint: fingerprint, traffic_source_fingerprint: sourceFingerprint });
  const baselineSourceText = 'frozen graph\n';
  const baselineSupplementText = 'DOMAIN,keep.test\n';
  const currentSupplementText = baselineSupplementText + added.join('\n') + '\n';
  const assets = {
    [`provider-${ids[0]}-domain.yaml`]: native(ids[0], ['keep.test']),
    [`provider-${ids[1]}-domain.yaml`]: native(ids[1], [...hosts, 'overlap.same.test'], 'domain_suffix_set:\n  - "same.test"\nip_cidr_set:\n  - "192.0.2.0/24"\n'),
    'geosite-extra.yaml': '# Generated by tools/generate-egern-from-cmfa.js\n# Frozen auxiliary source\nno_resolve: true\ngeoip_set:\n  - "CN"\n',
  };
  const snapshot = { schemaVersion: 1, assets, fusedMihomoHashes: Object.fromEntries(segments.map(row => [row.files.domain.source, hash(baseline.get(`${prefix}mihomo/${row.files.domain.source}`).toString())])),
    fusedPayloadFingerprint: fingerprint, trafficSourceFingerprint: sourceFingerprint,
    publishedAssets: Object.entries(assets).map(([file, text]) => ({ file, sha256: hash(text), bytes: Buffer.byteLength(text) })),
    publishedRendered: { source_entry_count: 8, dedup_removed: 7, global_exact_duplicates_removed: 6, empty_asset_count: 0 } };
  const snapshotBytes = zlib.gzipSync(JSON.stringify(snapshot));
  const receipt = { schema_version: 1, mode: 'partial-sync', baseline_commit: 'd'.repeat(40),
    baseline_manifest_sha256: hash(baselineManifestText), baseline_source_sha256: hash(baselineSourceText),
    baseline_supplemental_sha256: hash(baselineSupplementText), baseline_payload_sha256: fingerprint,
    local_delta: { added: [...added], removed: [] }, changed_segments: changes,
    source_receipt: { content: { sha256: hash(currentSupplementText), bytes: Buffer.byteLength(currentSupplementText) } },
    outputs: [...currentFiles].filter(([file]) => file !== unrelated).map(([file, bytes]) => ({ file, sha256: digest(bytes), bytes: bytes.length })),
    binding: { local_source_sha256: hash(currentSupplementText), traffic_source_fingerprint: sourceFingerprint, fused_payload_sha256: currentFingerprint } };
  return { receipt, snapshotBytes, baselineSnapshotBytes: snapshotBytes, baselineManifestText, baselineSourceText,
    baselineSupplementText, currentSupplementText, baselineFiles: new Map([...baseline].map(([file, bytes]) => [file, oid(bytes)])),
    currentFiles, readBaseline: file => baseline.get(file), targetSegmentId: ids[0],
    bindings: { trafficSourceFingerprint: sourceFingerprint, fusedPayloadFingerprint: currentFingerprint } };
}

function assetsFor(snapshot) {
  return new Map(Object.keys(snapshot.assets).map(file => {
    const id = file.slice(0, -5);
    return [file, { file, id, behavior: 'domain', sourceUrl: id.startsWith('provider-') ?
      `https://fastly.jsdelivr.net/gh/IvanSolis1989/Smart-Config-Kit@main/${prefix}mihomo/${id.slice('provider-'.length)}.yaml` : 'frozen-extra' }];
  }));
}

test('explicit receipt patches only two native exact domain sets and retains historical fingerprints', () => {
  const input = fixture();
  const snapshot = validateSupplementalPatch(input);
  const updated = generator.applySupplementalPatchToNativeSnapshot(snapshot, assetsFor(snapshot));
  assert.equal(updated.fusedPayloadFingerprint, input.receipt.baseline_payload_sha256);
  assert.equal(updated.assets['geosite-extra.yaml'], snapshot.assets['geosite-extra.yaml']);
  const ai = generator.parseFrozenRuleSet(updated.assets['provider-scki-fused-004-ai-domain.yaml']);
  assert.deepEqual([...ai.sets.domain_set].sort(), ['keep.test', ...hosts].sort());
  const ad = generator.parseFrozenRuleSet(updated.assets['provider-scki-fused-006-ad-domain.yaml']);
  assert.deepEqual([...ad.sets.domain_set], ['overlap.same.test']); // no optimizer subsumption
  assert.deepEqual([...ad.sets.domain_suffix_set], ['same.test']);
  assert.deepEqual([...ad.sets.ip_cidr_set], ['192.0.2.0/24']);
  assert.equal(updated.publishedRendered.source_entry_count, snapshot.publishedRendered.source_entry_count);
  assert.equal(updated.publishedRendered.dedup_removed, 7);
  assert.equal(updated.publishedRendered.global_exact_duplicates_removed, 6);
  assert.equal(Object.keys(updated.assets).filter(file => updated.assets[file] !== snapshot.assets[file]).length, 2);
});

for (const [name, mutate, expected] of [
  ['tampered frozen snapshot', input => { input.snapshotBytes = Buffer.from('changed'); }, /snapshot bytes changed/],
  ['tampered receipt baseline', input => { input.receipt.baseline_manifest_sha256 = '0'.repeat(64); }, /baseline binding/],
  ['changed provider definitions', input => { input.bindings.trafficSourceFingerprint = '0'.repeat(64); }, /current source\/payload binding/],
  ['changed receipt output hash', input => { input.receipt.outputs[0].sha256 = '0'.repeat(64); }, /output hash/],
  ['unrelated payload drift', input => { input.currentFiles.set(`${prefix}mihomo/unchanged-residual.yaml`, Buffer.from('changed')); }, /Unrelated frozen/],
  ['missing frozen asset', input => { input.currentFiles.delete(`${prefix}mihomo/unchanged-residual.yaml`); }, /inventory differs/],
  ['extra domain deletion', input => { input.currentFiles.set(`${prefix}mihomo/scki-fused-006-ad-domain.yaml`, Buffer.from(payload([]))); }, /outside receipt delta/],
  ['host widened to suffix', input => { input.currentFiles.set(`${prefix}mihomo/scki-fused-004-ai-domain.yaml`, Buffer.from(payload(['keep.test', ...hosts.map(host => `+.${host}`)]))); }, /outside receipt delta/],
  ['unapproved segment delta', input => { input.receipt.changed_segments[1].deleted.push('DOMAIN,unrelated.test'); }, /exceeds local receipt/],
  ['wrong target ownership', input => { input.targetSegmentId = 'scki-fused-006-ad'; }, /outside supplemental target/],
  ['missing receipt output', input => { input.receipt.outputs.pop(); }, /Missing Egern receipt output/],
]) test(`strict supplemental mode rejects ${name}`, () => {
  const input = fixture(); mutate(input);
  assert.throws(() => validateSupplementalPatch(input), expected);
});

test('staging copies all frozen auxiliary assets and rejects follow-rules in patch mode', () => {
  const snapshot = validateSupplementalPatch(fixture());
  const directory = fs.mkdtempSync(path.join(os.tmpdir(), 'scki-egern-patch-test-'));
  try {
    assert.throws(() => generator.generateNativeRuleSetsFromSnapshot(assetsFor(snapshot), snapshot, { outputDir: directory, followRules: true }), /block-foreign/);
    const stats = generator.generateNativeRuleSetsFromSnapshot(assetsFor(snapshot), snapshot, { outputDir: directory, followRules: false });
    assert.equal(stats.assetCount, 3);
    assert.equal(fs.readFileSync(path.join(directory, 'geosite-extra.yaml'), 'utf8'), snapshot.assets['geosite-extra.yaml']);
    assert.equal(stats.totalEntries, 8);
    assert.equal(stats.removedEntries, 7);
  } finally { fs.rmSync(directory, { recursive: true, force: true }); }
});

test('CLI preserves reuse-assets and requires an explicit separate supplemental receipt', () => {
  assert.deepEqual(generator.parseCliOptions(['--reuse-assets']), { reuseAssets: true, supplementalPatch: null });
  assert.deepEqual(generator.parseCliOptions(['--supplemental-patch', 'receipt.json']), { reuseAssets: true, supplementalPatch: 'receipt.json' });
  assert.throws(() => generator.parseCliOptions(['--supplemental-patch']), /incomplete/);
  assert.throws(() => generator.parseCliOptions(['--reuse-assets', '--supplemental-patch', 'receipt.json']), /separately/);
});

test('freezing genuinely rendered new staging permits subsequent ordinary strict reuse', () => {
  const snapshot = validateSupplementalPatch(fixture());
  const directory = fs.mkdtempSync(path.join(os.tmpdir(), 'scki-egern-patch-freeze-test-'));
  const reusedDirectory = fs.mkdtempSync(path.join(os.tmpdir(), 'scki-egern-patch-reuse-test-'));
  try {
    const stats = generator.generateNativeRuleSetsFromSnapshot(assetsFor(snapshot), snapshot, { outputDir: directory, followRules: false });
    const stagedManifest = { assets: { files: listGeneratedEgernAssetRecords(directory) }, source: {}, rendered: {
      source_entry_count: stats.totalEntries, dedup_removed: stats.removedEntries,
      global_exact_duplicates_removed: stats.globalExactDuplicates, empty_asset_count: stats.emptyAssets,
    } };
    const newSnapshot = packStagedOutput(directory, stagedManifest);
    const compiler = require('../build-fused-rule-sets');
    validateSnapshotBindings(newSnapshot, { fused: currentFusedHashes(), bindings: {
      trafficSourceFingerprint: compiler.trafficSourceFingerprint(), fusedPayloadFingerprint: compiler.fusedPayloadReceipt().digest,
    } });
    assert.equal(newSnapshot.supplementalPatch, undefined);
    assert.notEqual(newSnapshot.assets['provider-scki-fused-004-ai-domain.yaml'], snapshot.assets['provider-scki-fused-004-ai-domain.yaml']);
    const reuseStats = generator.generateNativeRuleSetsFromSnapshot(assetsFor(newSnapshot), newSnapshot, { outputDir: reusedDirectory, followRules: false });
    assert.deepEqual(reuseStats, stats);
    for (const [file, text] of Object.entries(newSnapshot.assets)) {
      assert.equal(fs.readFileSync(path.join(directory, file), 'utf8'), text);
      assert.equal(fs.readFileSync(path.join(reusedDirectory, file), 'utf8'), text);
    }
  } finally {
    fs.rmSync(directory, { recursive: true, force: true });
    fs.rmSync(reusedDirectory, { recursive: true, force: true });
  }
});
