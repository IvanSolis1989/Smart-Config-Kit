'use strict';

const crypto = require('node:crypto');
const fs = require('node:fs');
const path = require('node:path');
const zlib = require('node:zlib');
const { execFileSync } = require('node:child_process');

const ROOT = path.resolve(__dirname, '../..');
const SNAPSHOT_FILE = path.join(ROOT, 'rulesets/generated/egern-traffic-snapshot.json.gz');
const FUSED_DIR = path.join(ROOT, 'rulesets/generated/fused/mihomo');

function hash(text) {
  return crypto.createHash('sha256').update(String(text).replace(/\r\n/g, '\n'), 'utf8').digest('hex');
}

function gitShow(relative) {
  return execFileSync('git', ['show', `HEAD:${relative.replace(/\\/g, '/')}`], { cwd: ROOT, encoding: 'utf8', maxBuffer: 32 * 1024 * 1024 });
}

function currentFusedHashes() {
  const records = {};
  for (const file of fs.readdirSync(FUSED_DIR).filter((name) => name.endsWith('.yaml')).sort()) {
    records[file] = hash(fs.readFileSync(path.join(FUSED_DIR, file), 'utf8'));
  }
  return records;
}

function sourceBindings() {
  const { trafficSourceFingerprint, fusedPayloadReceipt } = require('../build-fused-rule-sets');
  return {
    trafficSourceFingerprint: trafficSourceFingerprint(),
    fusedPayloadFingerprint: fusedPayloadReceipt().digest,
  };
}

function packSnapshot(manifest, readAsset, publishedManifestText) {
  const assets = {};
  for (const record of manifest.assets.files) {
    const text = readAsset(record.file).replace(/\r\n/g, '\n');
    if (hash(text) !== record.sha256 || Buffer.byteLength(text, 'utf8') !== record.bytes) {
      throw new Error(`Published Egern asset differs from manifest: ${record.file}`);
    }
    assets[record.file] = text;
  }
  return {
    schemaVersion: 1,
    publishedManifestSha256: hash(publishedManifestText),
    publishedSource: manifest.source,
    publishedRendered: manifest.rendered,
    publishedAssets: manifest.assets.files,
    ...sourceBindings(),
    fusedMihomoHashes: currentFusedHashes(),
    assets,
  };
}

function saveSnapshot(snapshot) {
  const temporary = `${SNAPSHOT_FILE}.tmp-${process.pid}`;
  try {
    fs.writeFileSync(temporary, zlib.gzipSync(Buffer.from(JSON.stringify(snapshot), 'utf8'), { level: 9, mtime: 0 }));
    fs.renameSync(temporary, SNAPSHOT_FILE);
  } finally {
    if (fs.existsSync(temporary)) fs.rmSync(temporary);
  }
  return { file: SNAPSHOT_FILE, count: Object.keys(snapshot.assets).length, bytes: fs.statSync(SNAPSHOT_FILE).size };
}

function adoptPublishedHead() {
  if (fs.existsSync(SNAPSHOT_FILE)) throw new Error(`Snapshot already exists: ${SNAPSHOT_FILE}`);
  const manifestText = gitShow('rulesets/generated/egern/manifest.json');
  const manifest = JSON.parse(manifestText);
  return saveSnapshot(packSnapshot(manifest, (file) => gitShow(`rulesets/generated/egern/${file}`), manifestText));
}

function freezeCurrentOutput() {
  const manifestText = fs.readFileSync(path.join(ROOT, 'rulesets/generated/egern/manifest.json'), 'utf8');
  const manifest = JSON.parse(manifestText);
  return saveSnapshot(packSnapshot(manifest, (file) => fs.readFileSync(path.join(ROOT, 'rulesets/generated/egern', file), 'utf8'), manifestText));
}

function freezeStagedOutput(directory, manifest) {
  const manifestText = `${JSON.stringify(manifest, null, 2)}\n`;
  return saveSnapshot(packSnapshot(manifest, (file) => fs.readFileSync(path.join(directory, file), 'utf8'), manifestText));
}

function packStagedOutput(directory, manifest) {
  const manifestText = `${JSON.stringify(manifest, null, 2)}\n`;
  return packSnapshot(manifest, (file) => fs.readFileSync(path.join(directory, file), 'utf8'), manifestText);
}

function validateSnapshotAssets(snapshot) {
  if (snapshot.schemaVersion !== 1 || !snapshot.assets || !snapshot.fusedMihomoHashes) throw new Error('Invalid Egern traffic snapshot');
  for (const [file, text] of Object.entries(snapshot.assets)) {
    if (!/^[a-z0-9][a-z0-9._-]*\.yaml$/.test(file) || !text.startsWith('# Generated by tools/generate-egern-from-cmfa.js\n')) {
      throw new Error(`Invalid Egern snapshot asset: ${file}`);
    }
  }
  if (!Array.isArray(snapshot.publishedAssets) || snapshot.publishedAssets.length !== Object.keys(snapshot.assets).length) {
    throw new Error('Egern snapshot inventory is incomplete');
  }
  for (const record of snapshot.publishedAssets) {
    const text = snapshot.assets[record.file];
    if (typeof text !== 'string' || hash(text) !== record.sha256 || Buffer.byteLength(text, 'utf8') !== record.bytes) {
      throw new Error(`Egern snapshot asset hash mismatch: ${record.file}`);
    }
  }
  return snapshot;
}

function validateSnapshotBindings(snapshot, { fused, bindings }) {
  validateSnapshotAssets(snapshot);
  if (JSON.stringify(fused) !== JSON.stringify(snapshot.fusedMihomoHashes)) {
    throw new Error('Egern snapshot fused payload fingerprint mismatch; full rule refresh required');
  }
  if (snapshot.trafficSourceFingerprint !== bindings.trafficSourceFingerprint ||
      snapshot.fusedPayloadFingerprint !== bindings.fusedPayloadFingerprint) {
    throw new Error('Egern snapshot traffic source or fused payload fingerprint mismatch; full rule refresh required');
  }
  return snapshot;
}

function loadSnapshot() {
  return validateSnapshotBindings(JSON.parse(zlib.gunzipSync(fs.readFileSync(SNAPSHOT_FILE)).toString('utf8')),
    { fused: currentFusedHashes(), bindings: sourceBindings() });
}

const FUSED_PREFIX = 'rulesets/generated/fused/';
const PAYLOAD_DIRS = ['mihomo', 'clash', 'surge', 'quantumultx', 'egern', 'sing-box'];
const binaryHash = bytes => crypto.createHash('sha256').update(bytes).digest('hex');
const blobHash = bytes => crypto.createHash('sha1').update(`blob ${bytes.length}\0`).update(bytes).digest('hex');

// The receipt is an explicit transition, not permission to re-sign an old
// snapshot. Every unaffected asset must still be the baseline Git blob.
function validateSupplementalPatch({ receipt, snapshotBytes, baselineSnapshotBytes, baselineManifestText,
  baselineSourceText, baselineSupplementText, currentSupplementText, baselineFiles, currentFiles,
  readBaseline, bindings, targetSegmentId }) {
  const { assertTypedDomains, assertLocalDelta } = require('./snapshot-supplemental-patch');
  const compiler = require('../build-fused-rule-sets');
  const { toMihomoDomainPayload } = require('./mihomo-domain-payload');
  if (receipt.schema_version !== 1 || receipt.mode !== 'partial-sync' || !/^[a-f0-9]{40}$/.test(receipt.baseline_commit || '')) throw new Error('Invalid Egern supplemental receipt');
  if (!Buffer.from(snapshotBytes).equals(Buffer.from(baselineSnapshotBytes))) throw new Error('Egern baseline snapshot bytes changed');
  const snapshot = validateSnapshotAssets(JSON.parse(zlib.gunzipSync(baselineSnapshotBytes).toString('utf8')));
  const baselineManifest = JSON.parse(baselineManifestText);
  if (hash(baselineManifestText) !== receipt.baseline_manifest_sha256 || hash(baselineSourceText) !== receipt.baseline_source_sha256 ||
      hash(baselineSupplementText) !== receipt.baseline_supplemental_sha256 ||
      snapshot.fusedPayloadFingerprint !== receipt.baseline_payload_sha256 ||
      baselineManifest.payload_fingerprint !== receipt.baseline_payload_sha256 ||
      baselineManifest.traffic_source_fingerprint !== snapshot.trafficSourceFingerprint) throw new Error('Egern receipt baseline binding mismatch');
  if (receipt.baseline_egern_snapshot_sha256 && receipt.baseline_egern_snapshot_sha256 !== binaryHash(baselineSnapshotBytes)) throw new Error('Egern receipt snapshot hash mismatch');
  if (!receipt.binding || receipt.binding.fused_payload_sha256 !== bindings.fusedPayloadFingerprint ||
      receipt.binding.traffic_source_fingerprint !== bindings.trafficSourceFingerprint ||
      snapshot.trafficSourceFingerprint !== bindings.trafficSourceFingerprint ||
      receipt.binding.local_source_sha256 !== hash(currentSupplementText) ||
      receipt.source_receipt?.content?.sha256 !== hash(currentSupplementText) ||
      receipt.source_receipt?.content?.bytes !== Buffer.byteLength(String(currentSupplementText).replace(/\r\n/g, '\n'))) throw new Error('Egern receipt current source/payload binding mismatch');
  const delta = receipt.local_delta;
  if (!delta || !Array.isArray(delta.added) || !Array.isArray(delta.removed) || delta.removed.length) throw new Error('Egern supplemental transition requires additive exact DOMAIN rules');
  assertLocalDelta(compiler.parsePayloadEntries(baselineSupplementText), compiler.parsePayloadEntries(currentSupplementText), delta.added, delta.removed);
  if (!targetSegmentId) throw new Error('Missing Egern supplemental provider topology binding');
  if (!Array.isArray(receipt.changed_segments) || !receipt.changed_segments.length || !Array.isArray(receipt.outputs)) throw new Error('Incomplete Egern supplemental receipt');
  const allowedEntries = new Set(delta.added);
  const allowedOutputs = new Set();
  const changes = [];
  const ids = new Set();
  const expectedAdditions = new Map(delta.added.map(entry => [entry, 0]));
  for (const change of receipt.changed_segments) {
    if (ids.has(change.id)) throw new Error('Duplicate Egern changed segment');
    ids.add(change.id);
    assertTypedDomains(change.added, 'segment added');
    assertTypedDomains(change.deleted, 'segment deleted');
    if (![...change.added, ...change.deleted].length || [...change.added, ...change.deleted].some(entry => !allowedEntries.has(entry))) throw new Error('Egern segment delta exceeds local receipt');
    if (change.added.length && change.id !== targetSegmentId) throw new Error('Egern new DOMAIN assigned outside supplemental target');
    for (const entry of change.added) expectedAdditions.set(entry, expectedAdditions.get(entry) + 1);
    const row = baselineManifest.segments.find(segment => segment.id === change.id);
    if (!row?.files?.domain?.source || !row.files.domain.file) throw new Error('Egern receipt changed an unknown domain segment');
    const sourceFile = `${FUSED_PREFIX}mihomo/${row.files.domain.source}`;
    const beforeText = readBaseline(sourceFile).toString('utf8');
    if (snapshot.fusedMihomoHashes[row.files.domain.source] !== hash(beforeText)) throw new Error('Egern frozen Mihomo source differs from baseline');
    const afterBytes = currentFiles.get(sourceFile);
    if (!afterBytes) throw new Error('Missing Egern patched domain source');
    const before = compiler.parsePayloadEntries(beforeText), after = compiler.parsePayloadEntries(afterBytes.toString('utf8'));
    if (change.id === targetSegmentId && JSON.stringify(before) !== JSON.stringify(compiler.parsePayloadEntries(baselineSupplementText).map(toMihomoDomainPayload))) throw new Error('Egern supplemental baseline differs from isolated target');
    const adds = change.added.map(toMihomoDomainPayload), deletes = change.deleted.map(toMihomoDomainPayload);
    if (new Set(before).size !== before.length || new Set(after).size !== after.length || deletes.some(entry => !before.includes(entry)) || adds.some(entry => before.includes(entry))) throw new Error('Invalid Egern source DOMAIN delta');
    const expected = [...before.filter(entry => !deletes.includes(entry)), ...adds];
    if (JSON.stringify(expected) !== JSON.stringify(after)) throw new Error('Egern fused domain source differs outside receipt delta');
    const files = row.files;
    allowedOutputs.add(sourceFile);
    allowedOutputs.add(`${FUSED_PREFIX}mihomo/${files.domain.file}`);
    for (const platform of ['clash', 'surge', 'quantumultx']) {
      for (const file of files[platform]?.parts || [files[platform]?.file]) {
        if (!file) throw new Error('Incomplete baseline native asset topology');
        allowedOutputs.add(`${FUSED_PREFIX}${platform}/${file}`);
      }
    }
    for (const [platform, file] of [['egern', files.egern?.file], ['sing-box', files.sing_box?.source], ['sing-box', files.sing_box?.file]]) {
      if (!file) throw new Error('Incomplete baseline native asset topology');
      allowedOutputs.add(`${FUSED_PREFIX}${platform}/${file}`);
    }
    changes.push({ ...change, sourceFile, sourceText: afterBytes.toString('utf8') });
  }
  if ([...expectedAdditions.values()].some(count => count !== 1)) throw new Error('Egern receipt must assign every new DOMAIN to exactly one target');
  if (currentFiles.size !== baselineFiles.size || [...currentFiles.keys()].some(file => !baselineFiles.has(file))) throw new Error('Egern fused inventory differs from baseline');
  const outputRows = new Map();
  for (const record of receipt.outputs) {
    if (outputRows.has(record.file)) throw new Error('Duplicate Egern receipt output');
    outputRows.set(record.file, record);
    if (!record.file.startsWith(FUSED_PREFIX)) continue; // local MRS belongs to the upstream transition
    if (!allowedOutputs.has(record.file) || !currentFiles.has(record.file)) throw new Error('Egern receipt authorizes an unrelated fused asset');
    const bytes = currentFiles.get(record.file);
    if (binaryHash(bytes) !== record.sha256 || bytes.length !== record.bytes) throw new Error(`Egern receipt output hash mismatch: ${record.file}`);
  }
  for (const file of allowedOutputs) if (!outputRows.has(file)) throw new Error(`Missing Egern receipt output: ${file}`);
  for (const [file, bytes] of currentFiles) {
    if (!allowedOutputs.has(file) && blobHash(bytes) !== baselineFiles.get(file)) throw new Error(`Unrelated frozen fused asset changed: ${file}`);
  }
  // Preserve the historical fingerprints. The separate patch binding describes
  // the accepted transition; it is never persisted as a new canonical snapshot.
  snapshot.supplementalPatch = { receipt, changes, baselineSnapshotSha256: binaryHash(baselineSnapshotBytes) };
  return snapshot;
}

function loadSupplementalPatchSnapshot(receiptPath) {
  const receiptText = fs.readFileSync(path.resolve(ROOT, receiptPath), 'utf8');
  const receipt = JSON.parse(receiptText);
  if (!/^[a-f0-9]{40}$/.test(receipt.baseline_commit || '')) throw new Error('Egern receipt requires a full baseline commit');
  const git = args => execFileSync('git', args, { cwd: ROOT, maxBuffer: 64 * 1024 * 1024 });
  const readBaseline = relative => git(['show', `${receipt.baseline_commit}:${relative}`]);
  const sourcePath = receipt.source_receipt?.local_path;
  if (!/^rulesets\/supplemental\/clash\/[a-z0-9._-]+\.list$/.test(sourcePath || '')) throw new Error('Invalid Egern local supplemental receipt path');
  const tree = git(['ls-tree', '-r', receipt.baseline_commit, '--', ...PAYLOAD_DIRS.map(directory => FUSED_PREFIX + directory)]).toString('utf8');
  const baselineFiles = new Map(tree.trim().split('\n').filter(Boolean).map(line => {
    const match = /^100644 blob ([a-f0-9]{40})\t(.+)$/.exec(line);
    if (!match) throw new Error('Unexpected Egern baseline tree entry');
    return [match[2], match[1]];
  }));
  const compiler = require('../build-fused-rule-sets');
  const current = compiler.fusedPayloadReceipt();
  const baselineManifestText = readBaseline(`${FUSED_PREFIX}manifest.json`).toString('utf8');
  const mrs = JSON.parse(readBaseline('rulesets/generated/mihomo-mrs/manifest.json').toString('utf8'));
  const rows = mrs.converted.filter(row => row.id === receipt.provider_id);
  if (rows.length !== 1 || rows[0].generated.length !== 1 || rows[0].generated[0].behavior !== 'domain' || rows[0].source_url !== receipt.source_receipt.requested_url || !rows[0].source_url.split(/[?#]/)[0].endsWith(`/${sourcePath}`)) throw new Error('Egern receipt provider/local-source binding mismatch');
  const { buildMihomoRoutingGraph } = require('../../rulesets/source/routing-graph');
  const graph = buildMihomoRoutingGraph({ quicPolicy: 'block-foreign' });
  const topology = compiler.reuseSnapshotTopology({ providers: graph['rule-providers'], rules: graph.rules }, JSON.parse(baselineManifestText));
  const normalized = rows[0].generated[0].file.replace(/\.mrs$/, '');
  const targets = topology.segments.filter(segment => segment.sourceRules.some(rule => rule.startsWith(`RULE-SET,${normalized},`)));
  if (targets.length !== 1 || targets[0].sourceRules.length !== 1) throw new Error('Egern supplement requires an isolated target segment');
  const snapshot = validateSupplementalPatch({ receipt, snapshotBytes: fs.readFileSync(SNAPSHOT_FILE),
    baselineSnapshotBytes: readBaseline('rulesets/generated/egern-traffic-snapshot.json.gz'),
    baselineManifestText,
    baselineSourceText: readBaseline('rulesets/source/routing-graph.js').toString('utf8'),
    baselineSupplementText: readBaseline(sourcePath).toString('utf8'), currentSupplementText: fs.readFileSync(path.join(ROOT, sourcePath), 'utf8'),
    baselineFiles, currentFiles: current.files, readBaseline,
    bindings: { trafficSourceFingerprint: compiler.trafficSourceFingerprint(), fusedPayloadFingerprint: current.digest }, targetSegmentId: targets[0].id });
  const nativeDirectory = path.join(ROOT, 'rulesets/generated/egern');
  const nativeFiles = fs.readdirSync(nativeDirectory).filter(file => file.endsWith('.yaml'));
  if (nativeFiles.length !== Object.keys(snapshot.assets).length || nativeFiles.some(file => !Object.hasOwn(snapshot.assets, file))) throw new Error('Current Egern native inventory differs from frozen baseline');
  for (const file of nativeFiles) {
    if (hash(fs.readFileSync(path.join(nativeDirectory, file), 'utf8')) !== hash(snapshot.assets[file])) throw new Error(`Current Egern native asset differs from frozen baseline: ${file}`);
  }
  snapshot.supplementalPatch.receiptSha256 = hash(receiptText);
  return snapshot;
}

if (require.main === module && process.argv.includes('--adopt-head')) {
  try { console.log(JSON.stringify(adoptPublishedHead())); } catch (error) { console.error(error.message); process.exitCode = 1; }
}

